std::optional<InputKeys::key_references_variant> InputKeys::find_key(
    const KeyLabels& labels) {
  if (labels.size() == 0)
    return std::nullopt;
  const auto& list = InputKeys::all_keys();
  auto iterator_to_key_references_variant =
      std::find_if(list.begin(), list.end(), [&labels](const auto& key) {
        return std::visit(
            [&labels](auto&& arg) { return arg.get().has_same_labels(labels); },
            key);
      });
  if (iterator_to_key_references_variant == list.end()) {
    return std::nullopt;
  } else {
    return *iterator_to_key_references_variant;
  }
}

